import time, shutil, subprocess, tempfile, os, signal
from pathlib import Path
from degenerate.errors import GenerationError, OutputError

PREAMBLE = """
\\documentclass[11pt]{article}
\\usepackage[a4paper,top=2cm,left=2.5cm,right=2.5cm,bottom=2cm]{geometry}
\\usepackage[dvipsnames]{xcolor}
\\usepackage{amssymb,amsfonts,amsmath,amsthm}
\\usepackage{cite}
\\usepackage{hyperref}
\\usepackage{microtype}
\\usepackage{setspace}
\\onehalfspacing
\\numberwithin{equation}{section}
\\usepackage{tikz}
\\usetikzlibrary{positioning, calc, arrows.meta}
"""

def check_source(source):
    """
    Sanity check the source generated by the AI
    """
    # check for forbidden things
    do_not_want = [
    "\\usepackage",
    "\\input",
    "\\write",
    "\\include",
    "\\documentclass",
    "\\begin{document}"
    ]
    
    if any(x in source for x in do_not_want):
        raise OutputError("LaTeX code contains forbidden command")
        
    return source

def make_full_source(source, title, paper_author):

    source = check_source(source)

    full_source = PREAMBLE

    full_source = PREAMBLE+f"\n\\title{{{title}}}\n\\author{{{paper_author}}}"+"\n\\begin{document}\n\\maketitle"+source+"\n\\end{document}"
    
    # extract abstract
    start_abs = "\\begin{abstract}"
    end_abs = "\\end{abstract}"
    idx1 = source.find(start_abs)
    idx2 = source.find(end_abs, idx1 + len(start_abs))

    if idx1 != -1 and idx2 != -1:
        abstract = source[idx1 + len(start_abs):idx2].strip()
    else:
        abstract= "No abstract provided"

    return full_source, abstract
        
def make_paper(source, papername):
    """
    Creates LaTeX file from `source` and builds pdf
    """
    paper_dir = Path("papers")
    paper_dir.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        
        tex_env = {
        "PATH": os.environ["PATH"],   # so latexmk and pdflatex can be found
        "HOME": str(tmp),             
        "openin_any": "p",            # paranoid reading
        "openout_any": "p",           # paranoid writing
        }
        
        with open(tmp / f"{papername}.tex","w") as f:
            f.write(source)

        print("Building paper")
        cmd = ["latexmk", "-pdf",
               "-pdflatex=pdflatex -interaction=nonstopmode -no-shell-escape -halt-on-error %O %S",
               f"{papername}.tex"]

        proc = subprocess.Popen(cmd, cwd=tmp, env=tex_env,
                                stdin=subprocess.DEVNULL,
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                text=True, start_new_session=True)
        try:
            stdout, stderr = proc.communicate(timeout=60)
        except subprocess.TimeoutExpired as e:
            try:
                os.killpg(proc.pid, signal.SIGKILL)   # kill latexmk AND the pdflatex it started
            except ProcessLookupError:
                pass                                  # the group already ended by itself
            proc.communicate()                        # wait for it to end, close the pipes
            raise OutputError("Building pdf failed: timed out after 60s") from e

        if proc.returncode != 0:
            #print(stdout)
            #print(stderr)
            for f in [ f"{papername}.log"]:
                shutil.copy(tmp / f, paper_dir)
            raise OutputError(f"Building pdf failed (latexmk exit code {proc.returncode})")
        else:
            for f in [ f"{papername}.tex", f"{papername}.pdf"]:
                shutil.copy(tmp / f, paper_dir)

