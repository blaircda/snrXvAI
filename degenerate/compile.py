def save_failure(source, papername, reason):
    failures_dir = Path("failed")
    failures_dir.mkdir(parents=True, exist_ok=True)
    with open(failures_dir / f"{papername}_{reason}.tex","w", encoding="utf-8") as f:
        f.write(source) 


def check_source(source, papername):
    """
    Sanity check the source generated by the AI
    """
    # check for forbidden things
    do_not_want = [
    "\\usepackage",
    "\\input",
    "\\write",
    "\\include",
    "\\documentclass",
    "\\begin{document}"
    ]
    
    # strip enclosing markdown if present
    check = re.search(r"```\s*(?:(?:la)?tex)?(.*?)(?:```|\Z)", source, re.DOTALL | re.IGNORECASE)
    if check:
        source = check.group(1).strip()

    # next check for invalid commands
    # I don't do this first in case the model writes
    # "As instructed, I did not use \input" somewhere outside the actual LaTeX
    found = [x for x in do_not_want if x in source]
    if found:
        save_failure(source, papername, "failed_source_check")
        raise OutputError("LaTeX code contains forbidden commands: "+" ".join(found))
    return source

